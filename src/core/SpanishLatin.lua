-- Spanish-only 8x8 Latin glyph atlas used by engine Strings.
-- The atlas is generated in memory, so no manifest/charmap changes are needed.

local M = {}

local ROWS = {
  ".........##......##........#.......#.......#......##..#....#.......#......#.#.......#.......#....##..#.....#.......#.....#.#....",
  "...........#....#..#......#.......#.......#......#..##....#.......#.....#.....#....#.......#....#..##.....#.......#.............",
  ".........###....#..#.......#....#######..#####..##....#..#####..#.....#.#.....#...###............####....####...#...#...#...#...",
  "..##..#.#..#.....##.......#.#...#..........#....#.#...#.#.....#.#.....#.#.....#......#.....#.....#...#..#....#..#...#...#...#...",
  ".#..##...##.#............#...#..######.....#....#..#..#.#.....#.#.....#.#.....#...####.....#.....#...#..#....#..#...#...#...#...",
  "........................#######.#..........#....#...#.#.#.....#..#....#..#....#..#...#.....#.....#...#..#....#..#...#...#...#...",
  "........#####...........#.....#.#######..#####..#....##..#####....#####...#####...#####....#.....#...#...####....####....####...",
  "................................................................................................................................",
  "...##......##...................................................................................................................",
  "...##......##...................................................................................................................",
  "................................................................................................................................",
  "...##......##...................................................................................................................",
  ".##...##..####..................................................................................................................",
  "###..##...####..................................................................................................................",
  ".######...####..................................................................................................................",
  "...........##...................................................................................................................",
}

M.codes = {
  ["Á"] = 0x103, ["É"] = 0x104, ["Í"] = 0x105, ["Ñ"] = 0x106,
  ["Ó"] = 0x107, ["Ú"] = 0x108, ["Ü"] = 0x109,
  ["á"] = 0x10A, ["í"] = 0x10B, ["ñ"] = 0x10C,
  ["ó"] = 0x10D, ["ú"] = 0x10E, ["ü"] = 0x10F,
  ["¿"] = 0x110, ["¡"] = 0x111,
}

function M.make()
  local data = love.image.newImageData(128, 16)
  for y = 0, 15 do
    local row = ROWS[y + 1]
    for x = 0, 127 do
      if row:sub(x + 1, x + 1) == "#" then
        data:setPixel(x, y, 0, 0, 0, 1)
      else
        data:setPixel(x, y, 0, 0, 0, 0)
      end
    end
  end

  -- Font.drawCode ultimately calls love.graphics.draw(), which requires an
  -- Image (Drawable), not ImageData. Keep the generated pixels but create the
  -- actual drawable here. This is why opening Options previously closed LÖVE.
  local image = love.graphics.newImage(data)
  if image.setFilter then image:setFilter("nearest", "nearest") end

  local quads = {}
  for code = 0x103, 0x111 do
    local slot = code - 0x100
    quads[code] = love.graphics.newQuad(
      (slot % 16) * 8, math.floor(slot / 16) * 8,
      8, 8, 128, 16)
  end

  return image, quads
end

return M
