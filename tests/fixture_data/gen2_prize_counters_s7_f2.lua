local function word(args) return args[1] + args[2] * 256 end

function F.menuScript(scripts, key, silver, seen)
  seen = seen or {}
  if seen[key] then return nil end
  seen[key] = true
  for i, op in ipairs(scripts[key] or {}) do
    if op.op == "checkver" and silver then
      return F.menuScript(scripts, scripts[key][i + 1].script, false, seen)
    end
    if op.op == "loadmenu" then return key, i end
  end
  for _, op in ipairs(scripts[key] or {}) do
    if op.script then
      local found, at = F.menuScript(scripts, op.script, silver, seen)
      if found then return found, at end
    end
  end
end

function F.prizes(scripts, key, silver)
  local at
  key, at = F.menuScript(scripts, key, silver)
  local ops = scripts[key]
  local rows = {}
  for j = at + 1, #ops do
    local op = ops[j]
    if op.op == "ifequal" then
      local row = { label = ops[at].menu.items[op.value], branch = op.script }
      for _, step in ipairs(scripts[op.script]) do
        if step.op == "takecoins" then row.cost = word(step.args)
        elseif step.op == "giveitem" then row.item = step.item
        elseif step.op == "givepoke" then row.species, row.level = step.species, step.level
        elseif step.op == "givecoins" then row.amount = word(step.args)
        elseif step.op == "takemoney" then
          row.cost = (step.args[2] * 256 + step.args[3]) * 256 + step.args[4]
        elseif step.op == "sjump" or step.op == "end" then break end
      end
      rows[op.value] = row
    end
  end
  return rows
end

return F
